package DSA.Coding.DSABasic;

/**
 * Shared Definition for Singly-Linked List Node across all DSA problems.
 */
public class ListNode {
    public int val;
    public ListNode next;

    public ListNode() {}

    public ListNode(int val) {
        this.val = val;
    }

    public ListNode(int val, ListNode next) {
        this.val = val;
        this.next = next;
    }
}